import math

class UniswapV3Position:
    def __init__(self, price_current: float, price_lower: float, price_upper: float, capital_usd: float):
        self.p = price_current
        self.pa = price_lower
        self.pb = price_upper
        self.capital = capital_usd
        
        # Расчет параметра ликвидности L из доступного капитала
        sp = math.sqrt(self.p)
        spa = math.sqrt(self.pa)
        spb = math.sqrt(self.pb)
        
        # Капитал распределяется на x и y: Capital = x * P + y
        # x = L * (spb - sp) / (sp * spb)
        # y = L * (sp - spa)
        # Capital = L * [ (spb - sp) / spb + (sp - spa) ]
        denom = (spb - sp) / spb * self.p + (sp - spa)
        self.L = capital_usd / denom
        
        self.x = self.L * (spb - sp) / (sp * spb)
        self.y = self.L * (sp - spa)
        
    def get_portfolio_value(self, new_price: float) -> tuple[float, float, float]:
        # Возвращает (активы_x, активы_y, суммарная_стоимость_usd)
        spa = math.sqrt(self.pa)
        spb = math.sqrt(self.pb)
        
        if new_price <= self.pa:
            # Весь капитал перешел в токен X (падающий актив)
            x_total = self.L * (spb - spa) / (spa * spb)
            return x_total, 0.0, x_total * new_price
        elif new_price >= self.pb:
            # Весь капитал перешел в токен Y (растущий актив/стейблкоин)
            y_total = self.L * (spb - spa)
            return 0.0, y_total, y_total
        else:
            sp = math.sqrt(new_price)
            x = self.L * (spb - sp) / (sp * spb)
            y = self.L * (sp - spa)
            return x, y, x * new_price + y

# Пример расчета: Депозит $10,000 в пул ETH/USDC (диапазон $2800 - $3200 при цене $3000)
pos = UniswapV3Position(price_current=3000, price_lower=2800, price_upper=3200, capital_usd=10000)
val_drop = pos.get_portfolio_value(2600) # Падение ниже диапазона
print(f"Стоимость при падении до $2600: ${val_drop[2]:.2f} (100% в ETH, убыток: ${10000 - val_drop[2]:.2f})")
